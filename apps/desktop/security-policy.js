const NETWORK_PROTOCOLS = new Set(['ftp:', 'http:', 'https:', 'ws:', 'wss:']);
const DIAGNOSTIC_TRUNCATION_LINE = `${JSON.stringify({ event: 'truncated' })}\n`;
const DIAGNOSTIC_TRUNCATION_BYTES = Buffer.byteLength(DIAGNOSTIC_TRUNCATION_LINE, 'utf8');

export function createSecureWebPreferences() {
  return Object.freeze({
    nodeIntegration: false,
    nodeIntegrationInWorker: false,
    nodeIntegrationInSubFrames: false,
    contextIsolation: true,
    sandbox: true,
    webSecurity: true,
    allowRunningInsecureContent: false,
    webviewTag: false,
    navigateOnDragDrop: false,
    devTools: false,
  });
}

export function isAllowedEditorURL(candidate, editorOrigin) {
  try {
    const candidateUrl = new URL(candidate);
    const trustedUrl = new URL(editorOrigin);
    return candidateUrl.protocol === 'http:'
      && trustedUrl.protocol === 'http:'
      && candidateUrl.username === ''
      && candidateUrl.password === ''
      && trustedUrl.username === ''
      && trustedUrl.password === ''
      && candidateUrl.origin === trustedUrl.origin;
  } catch {
    return false;
  }
}

export function isAllowedNetworkRequest(candidate, editorOrigin) {
  try {
    const url = new URL(candidate);
    if (!NETWORK_PROTOCOLS.has(url.protocol)) return true;
    return url.protocol === 'http:' && isAllowedEditorURL(candidate, editorOrigin);
  } catch {
    return false;
  }
}

// Reconstruct the link generated by the Fonts dialog; never pass an arbitrary
// renderer-supplied URL to the operating system.
export function fontSearchTarget(candidate, editorPage, editorOrigin) {
  if (!isAllowedEditorURL(editorPage, editorOrigin)) return null;
  try {
    const name = new URL(candidate).searchParams.get('q');
    if (!name?.trim()) return null;
    const target = new URL('https://fonts2u.com/search.html');
    target.searchParams.set('q', name);
    return target.href === candidate ? target.href : null;
  } catch {
    return null;
  }
}

export function isAllowedSessionPermission(permission, requestingUrl, editorOrigin) {
  return permission === 'local-fonts'
    && isAllowedEditorURL(requestingUrl, editorOrigin);
}

export function isAllowedDesktopDownload({ isMainWindow, initiatorOrigin, mimeType, userGesture }, editorOrigin) {
  return isMainWindow === true
    && mimeType === 'application/pdf'
    && userGesture === true
    && typeof initiatorOrigin === 'string'
    && isAllowedEditorURL(initiatorOrigin, editorOrigin);
}

export function createDesktopDownloadDiagnostic(input, editorOrigin) {
  const initiatorOriginPresent = typeof input.initiatorOrigin === 'string'
    && input.initiatorOrigin.length > 0;
  return Object.freeze({
    event: input.phase,
    isMainWindow: input.isMainWindow,
    initiatorOriginPresent,
    initiatorIsEditor: initiatorOriginPresent
      && isAllowedEditorURL(input.initiatorOrigin, editorOrigin),
    mimeType: input.mimeType,
    userGesture: input.userGesture,
    policyAccepted: isAllowedDesktopDownload({
      isMainWindow: input.isMainWindow,
      initiatorOrigin: input.initiatorOrigin,
      mimeType: input.mimeType,
      userGesture: input.userGesture,
    }, editorOrigin),
    smokeSaveMode: input.smokeSaveMode,
    ...(input.state === undefined ? {} : { state: input.state }),
    ...(input.receivedBytes === undefined ? {} : { receivedBytes: input.receivedBytes }),
    ...(input.totalBytes === undefined ? {} : { totalBytes: input.totalBytes }),
  });
}

export function createBoundedDiagnosticWriter(writeLine, options = {}) {
  const maxRecords = options.maxRecords ?? 64;
  const maxBytes = options.maxBytes ?? 16_384;
  if (!Number.isSafeInteger(maxRecords) || maxRecords < 1) {
    throw new RangeError('maxRecords must be a positive safe integer');
  }
  if (!Number.isSafeInteger(maxBytes) || maxBytes < DIAGNOSTIC_TRUNCATION_BYTES) {
    throw new RangeError(`maxBytes must be at least ${DIAGNOSTIC_TRUNCATION_BYTES}`);
  }

  let recordCount = 0;
  let bytesWritten = 0;
  let truncated = false;
  const emit = (line) => {
    writeLine(line);
    recordCount += 1;
    bytesWritten += Buffer.byteLength(line, 'utf8');
  };

  return (record) => {
    if (truncated) return false;
    const line = `${JSON.stringify(record)}\n`;
    const lineBytes = Buffer.byteLength(line, 'utf8');
    const canWriteRecord = recordCount < maxRecords - 1
      && bytesWritten + lineBytes + DIAGNOSTIC_TRUNCATION_BYTES <= maxBytes;
    if (canWriteRecord) {
      emit(line);
      return true;
    }

    truncated = true;
    if (recordCount < maxRecords
      && bytesWritten + DIAGNOSTIC_TRUNCATION_BYTES <= maxBytes) {
      emit(DIAGNOSTIC_TRUNCATION_LINE);
    }
    return false;
  };
}
